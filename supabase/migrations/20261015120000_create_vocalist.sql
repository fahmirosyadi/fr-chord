create table if not exists public.vocalist (
  id bigint generated by default as identity primary key,
  name text not null,
  lowest_note text not null,
  highest_note text not null
);

alter table public.vocalist enable row level security;

create policy "Anyone can view vocalists"
  on public.vocalist
  as permissive
  for select
  to anon, authenticated
  using (true);

create policy "Supabase admins manage vocalists"
  on public.vocalist
  as permissive
  for all
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant select on table public.vocalist to anon, authenticated;
grant insert, update, delete on table public.vocalist to authenticated;
grant usage, select on sequence public.vocalist_id_seq to authenticated;
